namespace DragAndDropSystem.Core
{
    /// <summary>
    /// Опциональный интерфейс для предметов, которые определяют свой лимит стака.
    /// Реализуйте на адаптере вместе с IInventoryItem, чтобы задать максимальный размер стака
    /// для конкретного типа предмета.
    /// Если предмет не реализует этот интерфейс — используется дефолтный лимит стратегии/правила.
    /// </summary>
    public interface IStackSizeLimitable
    {
        /// <summary>
        /// Максимальное количество предметов данного типа в одном стаке
        /// </summary>
        int MaxStackSize { get; }
    }
}
