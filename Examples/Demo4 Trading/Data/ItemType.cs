namespace DragAndDropSystem.Examples.Trading.Data
{
    /// <summary>
    /// Типы предметов для системы торговли и экипировки
    /// </summary>
    public enum ItemType
    {
        /// <summary>
        /// Оружие (мечи, луки, посохи и т.д.)
        /// </summary>
        Weapon,

        /// <summary>
        /// Броня (доспехи, щиты и т.д.)
        /// </summary>
        Armor,

        /// <summary>
        /// Артефакты (кольца, амулеты и т.д.)
        /// </summary>
        Artifact,

        /// <summary>
        /// Расходуемые предметы (зелья, еда и т.д.)
        /// </summary>
        Consumable,

        /// <summary>
        /// Прочие предметы (квестовые, материалы и т.д.)
        /// </summary>
        Other
    }
}
